def generate_corpus(output_dir: str):
    root = Path(output_dir)
    root.mkdir(parents=True, exist_ok=True)

    all_texts = []
    for subject, texts in SUBJECTS.items():
        for i, text in enumerate(texts):
            all_texts.append((subject, i, text))

    written = 0

    # 1. Тематичні файли з предметів (30 файлів)
    for subject, texts in SUBJECTS.items():
        subdir = root / subject
        subdir.mkdir(exist_ok=True)
        for i, text in enumerate(texts):
            paragraphs = [text]
            # Додаємо трохи додаткового тексту для обсягу
            extra = random.sample([t for s, _, t in all_texts if s == subject and t != text], k=min(2, len(texts) - 1))
            for e in extra:
                sentences = e.split(". ")
                paragraphs.append(". ".join(sentences[: len(sentences) // 2 + 1]) + ".")
            body = "\n\n".join(paragraphs) + "\n"
            (subdir / f"{subject}_{i + 1:02d}.txt").write_text(body, encoding="utf-8")
            written += 1

    # 2. Навмисні дублікати (3 групи, 10 файлів)
    dup_dir = root / "duplicates_test"
    dup_dir.mkdir(exist_ok=True)

    # Група 1: Історія (3 файли-копії з різними іменами)
    src_hist = SUBJECTS["history"][0] + "\n\n" + SUBJECTS["history"][1] + "\n"
    for name in ["referat_kyiv_rus.txt", "homework_ivanov_hist.txt", "downloaded_article_copy.txt"]:
        (dup_dir / name).write_text(src_hist, encoding="utf-8")
        written += 1

    # Група 2: Фізика (3 файли-копії)
    src_phys = SUBJECTS["physics"][1] + "\n\n" + SUBJECTS["physics"][2] + "\n"
    for name in ["lab_report_v1.txt", "lab_report_backup.txt", "lab_report_final.txt"]:
        (dup_dir / name).write_text(src_phys, encoding="utf-8")
        written += 1

    # Група 3: Конституція (4 файли-копії)
    src_const = SUBJECTS["constitution"][0] + "\n\n" + SUBJECTS["constitution"][1] + "\n"
    for name in ["article_01.txt", "article_01_review.txt", "school_project_doc.txt", "printed_handout.txt"]:
        (dup_dir / name).write_text(src_const, encoding="utf-8")
        written += 1

    # 3. Великі файли для перевірки швидкості та стрес-тесту (10 файлів)
    stress_dir = root / "stress_bench"
    stress_dir.mkdir(exist_ok=True)
    for i in range(10):
        lines = []
        base = random.choice([t for _, _, t in all_texts])
        for _ in range(120):
            lines.append(base)
            words = base.split()
            random.shuffle(words)
            lines.append(" ".join(words))
        (stress_dir / f"bench_dataset_{i + 1:02d}.txt").write_text("\n\n".join(lines) + "\n", encoding="utf-8")
        written += 1

    print(f"Створено {written} файлів у {root.resolve()}")
    print("Структура:")
    print(" - 30 предметних файлів (історія, фізика, література, біологія, математика тощо)")
    print(" - 10 файлів-дублікатів (3 групи з ідентичним SHA-256 хешем)")
    print(" - 10 великих файлів у stress_bench/ для демонстрації швидкодії")
    print("\nДля запуску обробки на контролері:")
    print("  Увійдіть у меню [1] Контролер та введіть: batch")
    print(f"  (Або вкажіть шлях: {root.resolve()})")
    return root


if __name__ == "__main__":
    target = sys.argv[1] if len(sys.argv) > 1 else "demo_corpus"
    generate_corpus(target)
