def load_lang(data_dir: Path) -> str | None:
    path = Path(data_dir) / "lang.json"
    if not path.exists():
        return None
    try:
        lang = json.loads(path.read_text(encoding="utf-8")).get("lang")
        return lang if lang in TEXTS else None
    except (OSError, ValueError):
        return None


def save_lang(data_dir: Path, lang: str):
    if lang not in TEXTS:
        return
    path = Path(data_dir) / "lang.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"lang": lang}), encoding="utf-8")
